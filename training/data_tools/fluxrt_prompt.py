SLEEVE_CATEGORIES = {"tops", "dresses", "outerwear"}

# Our dataset categories -> app categories.
DATASET_CATEGORY = {"upper": "tops", "lower": "bottoms", "dress": "dresses"}


def normalize_category(raw: str | None) -> str | None:
    if not raw:
        return None
    v = raw.lower()
    for cat, keys in KEYWORD_MAP:
        if any(k in v for k in keys):
            return cat
    return None


def _any(text: str, keys: list[str]) -> bool:
    return any(k in text for k in keys)


def infer_sleeve_length(category=None, name=None, description=None, hint=None) -> str:
    text = " ".join(x for x in (category, name, description, hint) if x).lower()
    if not text:
        return "unknown"
    explicit = [("sleeveless", _any(text, EXPLICIT_SLEEVELESS)), ("short_sleeve", _any(text, EXPLICIT_SHORT)),
                ("long_sleeve", _any(text, EXPLICIT_LONG)), ("three_quarter_sleeve", _any(text, EXPLICIT_THREE_QUARTER))]
    hits = [k for k, v in explicit if v]
    if len(hits) == 1:
        return hits[0]
    if len(hits) > 1:
        return "unknown"
    generic = [("sleeveless", _any(text, SLEEVELESS_KEYS)), ("short_sleeve", _any(text, SHORT_SLEEVE_KEYS)),
               ("long_sleeve", _any(text, LONG_SLEEVE_KEYS)), ("three_quarter_sleeve", _any(text, THREE_QUARTER_KEYS))]
    hits = [k for k, v in generic if v]
    return hits[0] if len(hits) == 1 else "unknown"


def fluxrt_prompt(category=None, name=None, description=None, hint=None) -> str:
    """category may be an app category ("tops") or a dataset one ("upper")."""
    category = DATASET_CATEGORY.get(category, category)
    parts = [UNIVERSAL_BASE]
    cat = normalize_category(category)
    if cat:
        parts.append(CATEGORY_CLAUSES[cat])
    if cat and cat in SLEEVE_CATEGORIES:
        parts.append(SLEEVE_CLAUSE[infer_sleeve_length(category, name, description, hint)])
    for label, v in (("Selected item name", name), ("Item description", description), ("Additional item guidance", hint)):
        v = (v or "").strip()
        if v:
            parts.append(f"{label}: {v}.")
    return " ".join(parts)
