#!/usr/bin/env python3
"""Write configs/azyah_smoke_stage1.py: upstream Stage 1 config with the smoke-test
settings from upstream training/README.md. Every replacement must match exactly
once, so a change upstream fails loudly instead of silently training the wrong thing.

  python3 make_smoke_config.py <upstream training dir>

Runtime knobs (env vars read by the generated config):
  AZ_MAX_STEPS (20)  AZ_CKPT_INTERVAL (10)  AZ_AUTO_RESUME (0)  AZ_HSDP_SHARD (1)  AZ_SP_SIZE (1)
"""
import sys
from pathlib import Path

REPLACEMENTS = [
    ("TRAIN_RESOLUTION = (720, 1248)", "TRAIN_RESOLUTION = (480, 832)"),
    ("class Stage1ARConfig(ExpConfig):", "class AzyahSmokeStage1Config(ExpConfig):"),
    ('    exp_name: str = "default"', '    exp_name: str = "toy"'),
    ("    auto_resume: bool = False",
     '    auto_resume: bool = field(default_factory=lambda: os.getenv("AZ_AUTO_RESUME", "0") == "1")'),
    ("            min_temporal=49,\n            max_temporal=121,",
     "            min_temporal=49,\n            max_temporal=49,"),
    ("    max_train_steps: int = 10000000000",
     '    max_train_steps: int = field(default_factory=lambda: int(os.getenv("AZ_MAX_STEPS", "20")))'),
    ("    checkpoint_interval: int = 500",
     '    checkpoint_interval: int = field(default_factory=lambda: int(os.getenv("AZ_CKPT_INTERVAL", "10")))'),
    ("    lr_warmup_steps: int = 0", "    lr_warmup_steps: int = 5"),
    ("    sp_size: int = 1",
     '    sp_size: int = field(default_factory=lambda: int(os.getenv("AZ_SP_SIZE", "1")))'),
    ("    hsdp_shard_dim: int = 1", '    hsdp_shard_dim: int = field(default_factory=lambda: int(os.getenv("AZ_HSDP_SHARD", "1")))\n    # Azyah: Stage 1 LoRA (patches/stage1-lora.patch). AZ_STAGE1_LORA=0 = upstream full fine-tune.\n    stage1_lora: bool = field(default_factory=lambda: os.getenv("AZ_STAGE1_LORA", "1") == "1")\n    lora_rank: int = field(default_factory=lambda: int(os.getenv("AZ_LORA_RANK", "64")))\n    lora_alpha: int = field(default_factory=lambda: int(os.getenv("AZ_LORA_ALPHA", os.getenv("AZ_LORA_RANK", "64"))))'),
    ("    resume_optimizer: bool = False", "    resume_optimizer: bool = True  # Azyah: auto-resume restores the optimizer too"),
    ("    resume_dataloader: bool = False", "    resume_dataloader: bool = True"),
]


def main(training_dir: str) -> None:
    src = Path(training_dir) / "configs" / "stage1_ar.py"
    text = src.read_text()
    for old, new in REPLACEMENTS:
        n = text.count(old)
        if n != 1:
            sys.exit(f"upstream config changed: expected 1 match, found {n}: {old[:60]!r}")
        text = text.replace(old, new)
    header = '"""Azyah smoke test (generated by fluxrt-serverless/training/scripts/make_smoke_config.py)."""\n'
    out = src.parent / "azyah_smoke_stage1.py"
    out.write_text(header + text)
    print(f"wrote {out}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
